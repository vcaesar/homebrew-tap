    end

     on_arm do
      url "https://github.com/vcaesar/codg/releases/download/v#{version}/codg_darwin_arm64.zip"
      sha256 "438f6be9416d72bbbf7cb4d6680e29ef76ed3507a541f9d21ba5d051ccfddea2"
